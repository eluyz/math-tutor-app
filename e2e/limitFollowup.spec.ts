import {test,expect,type Page} from "@playwright/test";
import {shownFraction} from "./helpers/functions";
import {fractionText} from "./helpers/systems";
import {rational as r,addRational as add,subtractRational as sub,type Rational} from "../src/rational";
import {polishLearningText} from "./helpers/localization";
const button=(page:Page,name:string)=>page.getByRole("button",{name,exact:true});
const eq=(x:Rational,y:Rational)=>x.numerator*y.denominator===y.numerator*x.denominator;
for(const width of [375,1280])for(const en of [false,true])
test("MT-EDU-020 P1C "+width+"px "+(en?"EN":"PL"),async({page})=>{
 test.setTimeout(120000);const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
 await page.setViewportSize({width,height:900});await page.goto("/");
 if(en)await button(page,"English").click();
 await button(page,en?"University mathematics":"Matematyka na studia").click();
 await button(page,en?"Limits of functions":"Granice funkcji").click();
 await button(page,en?"Hard":"Trudny").click();
 await page.locator("button.exercise-item").filter({hasText:en?"Radical function limits at ±∞":"Granice z pierwiastkiem przy ±∞"}).click();
 await expect(page.locator(".question")).toHaveAttribute("data-template-id","limit-radical-infinity");
 const raw=await page.locator(".question").innerText();
 const parts=raw.match(/√\(\(([^()]+)\)²x²\+\(([^()]+)\)\)\+\(([^()]+)\)x\+\(([^()]+)\)/);
 if(!parts)throw Error("Cannot parse radical limit from UI: "+raw);
 const a=shownFraction(parts[1]),b=shownFraction(parts[2]),c=shownFraction(parts[3]),d=shownFraction(parts[4]);
 expect(a.numerator>0n&&b.numerator>0n).toBe(true);
 const direction=raw.includes("x→−∞")?-1:1;
 const slope=direction===1?add(a,c):sub(c,a);
 const expected=slope.numerator===0n?"finite":
  (slope.numerator>0n)===(direction===1)?"positive-infinity":"negative-infinity";
 const check=button(page,en?"Check":"Sprawdź");
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
 await page.locator("#answer").selectOption(expected==="finite"?"positive-infinity":"finite");
 if(expected!=="finite")await page.locator("#limit-value").fill("0");
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
 await page.locator("#answer").selectOption(expected);
 if(expected==="finite")await page.locator("#limit-value").fill(fractionText(d));
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback correct");
 await button(page,en?"Show solution":"Pokaż rozwiązanie").click();
 await button(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
 await expect(page.locator(".solution-panel")).toContainText(en?"Final answer":"Końcowa odpowiedź");
 await page.locator("button.exercise-item").filter({hasText:en?"Piecewise continuity and Heine criterion":"Ciągłość przedziałami i kryterium Heinego"}).click();
 await expect(page.locator(".question")).toHaveAttribute("data-template-id","limit-piecewise-heine");
 const piecewise=await page.locator(".question").innerText();
 const limits=[...piecewise.matchAll(/\(([^()]+)\)\+\(([^()]+)\)·\(x−\(([^()]+)\)\)/g)];
 const atPoint=piecewise.match(/;\s*([^;\s]+) (?:dla|for) x=/);
 if(limits.length!==2||!atPoint)throw Error("Cannot parse Heine question: "+piecewise);
 const L=shownFraction(limits[0][1]),R=shownFraction(limits[1][1]),F=shownFraction(atPoint[1]);
 const classification=!eq(L,R)?"jump":eq(L,F)?"continuous":"removable";
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
 await page.locator("#answer").selectOption(classification==="continuous"?"removable":"continuous");
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
 await page.locator("#answer").selectOption(classification);
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback correct");
 await button(page,en?"Show solution":"Pokaż rozwiązanie").click();
 await button(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
 await expect(page.locator(".solution-panel")).toContainText(en?"Final answer":"Końcowa odpowiedź");
 if(en)expect(await page.locator("main").innerText()).not.toMatch(polishLearningText);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 expect(errors).toEqual([]);
});
