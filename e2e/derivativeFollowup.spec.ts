import {test,expect,type Page} from "@playwright/test";
import {shownFraction} from "./helpers/functions";
import {fractionText} from "./helpers/systems";
import {rational as r,addRational as add,subtractRational as sub,multiplyRational as mul,divideRational as div,type Rational} from "../src/rational";
import {polishLearningText} from "./helpers/localization";
const button=(page:Page,name:string)=>page.getByRole("button",{name,exact:true});
const sq=(x:Rational)=>mul(x,x);
const quadratic=(a:Rational,b:Rational,c:Rational,x:Rational)=>add(add(mul(a,sq(x)),mul(b,x)),c);
for(const width of [375,1280])for(const en of [false,true])
test("MT-EDU-021 P2A "+width+"px "+(en?"EN":"PL"),async({page})=>{
 test.setTimeout(120000);const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
 await page.setViewportSize({width,height:900});await page.goto("/");
 if(en)await button(page,"English").click();
 await button(page,en?"University mathematics":"Matematyka na studia").click();
 await button(page,en?"Derivatives":"Pochodne").click();
 await button(page,en?"Hard":"Trudny").click();
 const check=button(page,en?"Check":"Sprawdź");
 await page.locator("button.exercise-item").filter({hasText:en?"Derivative of a quadratic-over-linear quotient":"Pochodna ilorazu wielomianu kwadratowego i liniowego"}).click();
 await expect(page.locator(".question")).toHaveAttribute("data-template-id","derivative-quadratic-quotient");
 const qtext=await page.locator(".question").innerText();
 const hMatch=qtext.match(/x=([^\s.]+)/),parts=qtext.match(/f\(x\)=\(\(([^()]+)\)x²\+\(([^()]+)\)x\+\(([^()]+)\)\)\/\(\(([^()]+)\)x\+\(([^()]+)\)\)/);
 if(!hMatch||!parts)throw Error("Cannot parse displayed quadratic quotient: "+qtext);
 const [a,b,c,d,e,h]=[...parts.slice(1),hMatch[1]].map(shownFraction);
 const D=add(mul(d,h),e),N=quadratic(a,b,c,h),Nprime=add(mul(r(2),mul(a,h)),b);
 const answer=div(sub(mul(Nprime,D),mul(N,d)),sq(D));
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
 await page.locator("#answer").fill(fractionText(add(answer,r(1))));await check.click();
 await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
 await page.locator("#answer").fill(fractionText(answer));await check.click();
 await expect(page.locator(".feedback")).toHaveClass("feedback correct");
 await button(page,en?"Show solution":"Pokaż rozwiązanie").click();
 await button(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
 await expect(page.locator(".solution-panel")).toContainText(en?"Final answer":"Końcowa odpowiedź");
 await page.locator("button.exercise-item").filter({hasText:en?"Derivative of a logarithm of a quadratic":"Pochodna logarytmu funkcji kwadratowej"}).click();
 await expect(page.locator(".question")).toHaveAttribute("data-template-id","derivative-log-quadratic");
 const log=await page.locator(".question").innerText();
 const hm=log.match(/x=([^\s.]+)/),lm=log.match(/f\(x\)=ln\(\(([^()]+)\)x²\+\(([^()]+)\)x\+\(([^()]+)\)\)/);
 if(!hm||!lm)throw Error("Cannot parse displayed logarithmic quadratic: "+log);
 const [aa,bb,cc,hh]=[...lm.slice(1),hm[1]].map(shownFraction);
 const U=quadratic(aa,bb,cc,hh),Up=add(mul(r(2),mul(aa,hh)),bb);
 expect(U.numerator).toBeGreaterThan(0n);
 const expected=div(Up,U);
 await check.click();await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
 await page.locator("#answer").fill(fractionText(add(expected,r(1))));await check.click();
 await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
 await page.locator("#answer").fill(fractionText(expected));await check.click();
 await expect(page.locator(".feedback")).toHaveClass("feedback correct");
 await button(page,en?"Show solution":"Pokaż rozwiązanie").click();
 await button(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
 await expect(page.locator(".solution-panel")).toContainText(en?"Final answer":"Końcowa odpowiedź");
 if(en)expect(await page.locator("main").innerText()).not.toMatch(polishLearningText);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 expect(errors).toEqual([]);
});
