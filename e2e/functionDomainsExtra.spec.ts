import {test,expect,type Page} from "@playwright/test";
import {shownFraction} from "./helpers/functions";
import {rational as r,subtractRational as sub} from "../src/rational";
import {formatRational as f} from "../src/answers";
import {polishLearningText} from "./helpers/localization";

const btn=(page:Page,name:string)=>page.getByRole("button",{name,exact:true});
for(const width of [375,1280])for(const en of [false,true])
test(`MT-EDU-015B P2A ${width}px ${en?"EN":"PL"}: tangent and mixed domains`,async({page})=>{
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.setViewportSize({width,height:920});await page.goto("/");
  if(en)await btn(page,"English").click();
  await btn(page,en?"University mathematics":"Matematyka na studia").click();
  await btn(page,en?"Functions":"Funkcje").click();
  await btn(page,en?"Medium":"Średni").click();
  await page.getByRole("button",{name:en?/Tangent domain and periodic exclusions/:/Dziedzina tangensa i wykluczenia okresowe/}).click();
  await expect(page.locator(".question")).toHaveAttribute("data-template-id","function-tangent-domain");
  const question=await page.locator(".question").innerText();
  const parts=question.match(/tan\(\((\d+)\)x \+ \(([^()]*)\)π\)/);
  if(!parts)throw Error("Unrecognized tangent formula");
  const origin=f(sub(r(1,2),shownFraction(parts[2])));
  await expect(page.locator("#answer option[value='tan:correct']")).toContainText(`(${origin} + k)π)/${parts[1]}`);
  await btn(page,en?"Check":"Sprawdź").click();
  await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
  await page.locator("#answer").selectOption("tan:zeros");
  await btn(page,en?"Check":"Sprawdź").click();
  await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
  await page.locator("#answer").selectOption("tan:correct");
  await btn(page,en?"Check":"Sprawdź").click();
  await expect(page.locator(".feedback")).toHaveClass("feedback correct");
  await btn(page,en?"Show solution":"Pokaż rozwiązanie").click();
  await btn(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
  await expect(page.locator(".solution-panel")).toContainText("k∈ℤ");
  await page.getByRole("button",{name:en?/Domain: radicals and logarithms/:/Dziedzina: pierwiastek i logarytm/}).click();
  await expect(page.locator(".question")).toHaveAttribute("data-template-id","function-mixed-domain");
  await btn(page,en?"Check":"Sprawdź").click();
  await expect(page.locator(".feedback")).toHaveClass("feedback invalid");
  const options=await page.locator("#answer option").evaluateAll(nodes=>nodes.map(n=>({value:(n as HTMLOptionElement).value,label:(n as HTMLOptionElement).textContent?.trim()})));
  const wrong=options.find(o=>o.label==="ℝ");
  if(!wrong)throw Error("Missing universal-set distractor");
  await page.locator("#answer").selectOption(wrong.value);
  await btn(page,en?"Check":"Sprawdź").click();
  await expect(page.locator(".feedback")).toHaveClass("feedback incorrect");
  await btn(page,en?"Show solution":"Pokaż rozwiązanie").click();
  await btn(page,en?"Show all steps":"Pokaż wszystkie kroki").click();
  await expect(page.locator(".solution-panel")).toContainText(en?"Domain":"Dziedzina");
  if(en)expect(await page.locator("main").innerText()).not.toMatch(polishLearningText);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
